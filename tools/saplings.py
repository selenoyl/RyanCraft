def sapling(sp):
    bark, _, wood, leaf, bloom = TREES[sp]
    l, b = hexc(leaf), hexc(bark)
    if sp == "black_walnut": l = shade(l, .82)              # pale leaflets need more weight at this size
    stem_dark, stem_light = shade(b, .72), shade(b, 1.05)
    if sp == "sycamore": stem_light, stem_dark = (214, 206, 186), (170, 160, 140)
    if sp in ("black_cherry", "black_walnut", "eastern_redbud"): stem_dark, stem_light = shade(b, 1.1), shade(b, 1.4)
    bl = hexc(bloom) if bloom else l
    accent = (200, 46, 40) if sp == "red_maple" else (150, 170, 60)
    pal = {"o": shade(l, .5), "d": shade(l, .7), "m": shade(l, .88), "l": l, "h": shade(l, 1.18),
           "b": stem_dark, "B": stem_light, "p": shade(bl, .75), "P": bl, "Q": shade(bl, 1.08), "y": accent}
    rows = [r for r in ART[sp].strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (sp, [len(r) for r in rows])
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0)); px = img.load()
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c != ".": px[x, y] = tuple(min(255, v) for v in pal[c]) + (255,)
    return img

if __name__ == "__main__":
    out = os.path.join(os.path.dirname(__file__), "../src/main/resources/assets/ryancraft/textures/block")
    for sp in ART: sapling(sp).save(f"{out}/{sp}_sapling.png")
