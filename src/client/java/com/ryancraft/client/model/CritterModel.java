package com.ryancraft.client.model;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.ryancraft.RyanCraft;
import com.ryancraft.client.render.CritterRenderState;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.util.Mth;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * A model built from assets/ryancraft/critter_models/&lt;name&gt;.json (generated by tools/critters.py),
 * animated by each part's role: head, quadruped legs, bird legs and wings, tails, fish tails.
 */
public class CritterModel extends EntityModel<LivingEntityRenderState> {
    private static final Map<String, JsonObject> SPECS = new HashMap<>();
    private final Map<String, ModelPart> roles = new HashMap<>();
    private final java.util.List<ModelPart> bodyParts = new java.util.ArrayList<>(), legParts = new java.util.ArrayList<>();
    /** How far the body drops when sitting: the leg length. */
    private float sitDrop;

    public CritterModel(ModelPart root, String name) {
        super(root);
        for (JsonElement el : spec(name).getAsJsonArray("parts")) {
            JsonObject p = el.getAsJsonObject();
            String r = p.has("role") && !p.get("role").isJsonNull() ? p.get("role").getAsString() : "";
            ModelPart mp = root.getChild(p.get("name").getAsString());
            if (r.startsWith("leg")) {
                legParts.add(mp);
                for (JsonElement be : p.getAsJsonArray("boxes")) sitDrop = Math.max(sitDrop, be.getAsJsonObject().getAsJsonArray("size").get(1).getAsFloat());
            } else bodyParts.add(mp);
            if (p.has("role") && !p.get("role").isJsonNull()) {
                roles.put(p.get("role").getAsString(), root.getChild(p.get("name").getAsString()));
            }
        }
    }

    public static ModelLayerLocation layer(String name) {
        return new ModelLayerLocation(RyanCraft.id(name), "main");
    }

    public static synchronized JsonObject spec(String name) {
        return SPECS.computeIfAbsent(name, n -> {
            String path = "/assets/ryancraft/critter_models/" + n + ".json";
            try (InputStream in = CritterModel.class.getResourceAsStream(path)) {
                if (in == null) throw new IllegalStateException("Missing " + path);
                return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            } catch (Exception e) {
                throw new IllegalStateException("Couldn't read " + path, e);
            }
        });
    }

    public static LayerDefinition createLayer(String name) {
        JsonArray tex = spec(name).getAsJsonArray("texture");
        return LayerDefinition.create(createMesh(name), tex.get(0).getAsInt(), tex.get(1).getAsInt());
    }

    public static MeshDefinition createMesh(String name) {
        JsonObject spec = spec(name);
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        for (JsonElement el : spec.getAsJsonArray("parts")) {
            JsonObject p = el.getAsJsonObject();
            CubeListBuilder cubes = CubeListBuilder.create();
            // Anti z-fighting: where boxes overlap with faces at the same height, the GPU flickers between them. Every box gets a
            // slightly different, invisibly small inflation (attached parts a bit more than the body) so no two faces are coplanar.
            String role = p.has("role") && !p.get("role").isJsonNull() ? p.get("role").getAsString() : "";
            float inflate = role.equals("body") || role.equals("soar_body") || role.equals("fish_body") ? 0f : 0.03f;
            int boxIndex = 0;
            for (JsonElement be : p.getAsJsonArray("boxes")) {
                JsonObject b = be.getAsJsonObject();
                float grow = inflate + 0.006f * boxIndex++;
                JsonArray uv = b.getAsJsonArray("uv"), from = b.getAsJsonArray("from"), size = b.getAsJsonArray("size");
                cubes.texOffs(uv.get(0).getAsInt(), uv.get(1).getAsInt())
                        .mirror(b.has("mirror") && b.get("mirror").getAsBoolean())
                        .addBox(from.get(0).getAsFloat(), from.get(1).getAsFloat(), from.get(2).getAsFloat(),
                                size.get(0).getAsFloat(), size.get(1).getAsFloat(), size.get(2).getAsFloat(),
                                new net.minecraft.client.model.geom.builders.CubeDeformation(grow));
            }
            JsonArray pv = p.getAsJsonArray("pivot"), rot = p.getAsJsonArray("rot");
            root.addOrReplaceChild(p.get("name").getAsString(), cubes, PartPose.offsetAndRotation(
                    pv.get(0).getAsFloat(), pv.get(1).getAsFloat(), pv.get(2).getAsFloat(),
                    rot.get(0).getAsFloat(), rot.get(1).getAsFloat(), rot.get(2).getAsFloat()));
        }
        return mesh;
    }

    @Override
    public void setupAnim(LivingEntityRenderState state) {
        super.setupAnim(state);
        boolean flying = state instanceof CritterRenderState c && c.flying;
        float pos = state.walkAnimationPos, speed = state.walkAnimationSpeed, age = state.ageInTicks;
        float swing = Mth.cos(pos * 0.6662f) * 1.4f * speed;

        ModelPart head = roles.get("head");
        if (head != null) {
            head.xRot += state.xRot * Mth.DEG_TO_RAD;
            head.yRot += state.yRot * Mth.DEG_TO_RAD;
        }
        // Staged antlers: each stage's part appears once the animal reaches it, and turns with the head
        int antlers = state instanceof CritterRenderState c ? c.antlers : -1, rack = state instanceof CritterRenderState c2 ? c2.rack : 0;
        for (var e : roles.entrySet()) {
            String role = e.getKey();
            if (!role.startsWith("antler_")) continue;
            ModelPart a = e.getValue();
            a.visible = role.equals("antler_rare") ? antlers >= 4 && rack > 0 : antlers >= (role.charAt(7) - '0');
            if (head != null) { a.xRot = head.xRot; a.yRot = head.yRot; a.zRot = head.zRot; }
        }
        rotX("leg_rf", swing); rotX("leg_lb", swing);
        rotX("leg_lf", -swing); rotX("leg_rb", -swing);
        // Soaring birds: wings folded when perched; spread wide (with a slow, shallow beat) and the body level in flight
        if (flying) {
            boolean rising = state instanceof CritterRenderState c && c.rising;
            float glide = rising ? 1.05f + Mth.sin(age * 0.85f) * 0.7f     // climbing: deep, steady wingbeats
                                 : 1.35f + Mth.sin(age * 0.18f) * 0.12f;  // level or sinking: a held glide
            rotZ("soar_wing_r", glide); rotZ("soar_wing_l", -glide);
            rotX("soar_body", 0.35f);
        }
        // Birds with separate flight wings: folded wings hide in the air, broad ones beat instead
        ModelPart flyR = roles.get("fly_wing_r"), flyL = roles.get("fly_wing_l");
        if (flyR != null && flyL != null) {
            flyR.visible = flyL.visible = flying;
            ModelPart wr = roles.get("wing_r"), wl = roles.get("wing_l");
            if (wr != null) wr.visible = !flying;
            if (wl != null) wl.visible = !flying;
            float beat = Mth.sin(age * 0.7f) * 0.55f;
            flyR.zRot = beat; flyL.zRot = -beat;
        }
        if (flying) {
            rotX("leg_r", 1.1f); rotX("leg_l", 1.1f);
            float flap = 0.3f + Mth.sin(age * 1.9f) * 0.9f;
            rotZ("wing_r", flap); rotZ("wing_l", -flap);
        } else {
            rotX("leg_r", swing); rotX("leg_l", -swing);
        }
        ModelPart tail = roles.get("tail");
        if (tail != null) {
            tail.yRot += Mth.sin(age * 0.12f) * 0.12f + Mth.sin(pos * 0.6662f) * 0.35f * speed;
        }
        // Sitting (a crow told to stay, or perched on a shoulder): legs tucked under, body settled down by the leg length
        if (state instanceof CritterRenderState cs && cs.sitting && sitDrop > 0) {
            for (ModelPart l : legParts) l.visible = false;
            for (ModelPart b : bodyParts) b.y += sitDrop * 0.9f;
        } else for (ModelPart l : legParts) l.visible = true;
        ModelPart whaleTail = roles.get("whale_tail");                 // whale flukes beat up and down
        if (whaleTail != null) {                                     // a slow idle sway, beating harder and faster the faster it swims
            float sp = Math.min(1.0f, speed * 2.5f);
            whaleTail.xRot = Mth.sin(age * (0.1f + 0.14f * sp)) * (0.14f + 0.3f * sp);
        }
        ModelPart fishTail = roles.get("fish_tail");
        if (fishTail != null) {
            fishTail.yRot = Mth.sin(age * 0.6f) * (state.isInWater ? 0.45f : 0.7f);
        }
    }

    private void rotX(String role, float a) { ModelPart p = roles.get(role); if (p != null) p.xRot += a; }
    private void rotZ(String role, float a) { ModelPart p = roles.get(role); if (p != null) p.zRot += a; }
}
